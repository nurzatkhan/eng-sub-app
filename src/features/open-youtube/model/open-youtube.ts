import { toast } from "sonner";
import { useMediaStore } from "@/entities/media";
import { normalizeCues, useSubtitleStore } from "@/entities/subtitle";
import { YoutubeCaptionsRequestError, fetchYoutubeCaptions } from "@/shared/api";
import { parseYoutubeStartTime, parseYoutubeVideoId } from "@/shared/lib/youtube";

let pending: AbortController | null = null;

/** Opens a YouTube link in the player and loads its English captions. Returns false if it isn't a YouTube link. */
export function openYoutube(link: string): boolean {
  const videoId = parseYoutubeVideoId(link);
  if (!videoId) return false;

  useMediaStore.getState().loadYoutube(videoId, parseYoutubeStartTime(link));
  useSubtitleStore.getState().clear();
  void loadCaptions(videoId);
  return true;
}

async function loadCaptions(videoId: string) {
  pending?.abort();
  const controller = new AbortController();
  pending = controller;

  const toastId = toast.loading("Загружаю субтитры с YouTube…");
  try {
    const captions = await fetchYoutubeCaptions(videoId, controller.signal);
    const cues = normalizeCues(captions.lines);
    useMediaStore.getState().setTitle(captions.title);
    useSubtitleStore.getState().setCues(cues, "YouTube");
    toast.success(`Субтитры: ${cues.length} строк`, {
      id: toastId,
      description: captions.autoGenerated ? "Автоматические субтитры YouTube — возможны ошибки" : undefined,
    });
  } catch (e) {
    if (controller.signal.aborted) {
      toast.dismiss(toastId);
      return;
    }
    const code = e instanceof YoutubeCaptionsRequestError ? e.code : "upstream";
    const messages: Record<string, [string, string?]> = {
      "no-english-captions": ["У этого видео нет английских субтитров", "Можно загрузить свой файл .srt / .vtt"],
      blocked: [
        "YouTube не отдаёт субтитры серверу сайта",
        "YouTube блокирует запросы с облачных серверов. Запустите приложение локально (pnpm dev) или загрузите свой .srt / .vtt",
      ],
      unavailable: ["Видео недоступно"],
    };
    const [title, description] = messages[code] ?? ["Не удалось загрузить субтитры с YouTube"];
    toast.error(title, { id: toastId, description, duration: code === "blocked" ? 12_000 : undefined });
  } finally {
    if (pending === controller) pending = null;
  }
}
