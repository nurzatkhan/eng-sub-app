import "server-only";
import { cacheLife } from "next/cache";
import type { YoutubeCaptionLine, YoutubeCaptions } from "./types";

// YouTube's internal ("innertube") player API, as used by the Android app.
// It is undocumented: if captions stop loading, the client version likely needs a bump.
const PLAYER_ENDPOINT = "https://www.youtube.com/youtubei/v1/player?prettyPrint=false";
const ANDROID_CLIENT = { clientName: "ANDROID", clientVersion: "20.10.38", androidSdkVersion: 34, hl: "en" };
const ANDROID_UA = `com.google.android.youtube/${ANDROID_CLIENT.clientVersion} (Linux; U; Android 14)`;

type CaptionTrack = { baseUrl: string; languageCode: string; kind?: string };

type PlayerResponse = {
  playabilityStatus?: { status?: string; reason?: string };
  videoDetails?: { title?: string };
  captions?: { playerCaptionsTracklistRenderer?: { captionTracks?: CaptionTrack[] } };
};

/** Expected failures are returned, not thrown: errors lose their class when crossing a "use cache" boundary. */
export type YoutubeCaptionsResult =
  | { ok: true; captions: YoutubeCaptions }
  | { ok: false; code: "unavailable" | "blocked" | "no-english-captions"; message: string };

/** Throws only on network/upstream errors, so those aren't cached. */
export async function getYoutubeCaptions(videoId: string): Promise<YoutubeCaptionsResult> {
  "use cache";
  cacheLife("days");

  const res = await fetch(PLAYER_ENDPOINT, {
    method: "POST",
    headers: { "Content-Type": "application/json", "User-Agent": ANDROID_UA },
    body: JSON.stringify({ context: { client: ANDROID_CLIENT }, videoId }),
  });
  if (!res.ok) throw new Error(`YouTube responded ${res.status}`);
  const player = (await res.json()) as PlayerResponse;

  // YouTube asks datacenter IPs (e.g. Vercel) to "sign in to confirm you're not a bot"
  if (player.playabilityStatus?.status === "LOGIN_REQUIRED") {
    return { ok: false, code: "blocked", message: player.playabilityStatus.reason ?? "Blocked by YouTube" };
  }
  if (player.playabilityStatus?.status !== "OK") {
    return { ok: false, code: "unavailable", message: player.playabilityStatus?.reason ?? "Video is unavailable" };
  }

  const tracks = player.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  const english = tracks.filter((t) => t.languageCode === "en" || t.languageCode.startsWith("en-"));
  // prefer human-made subtitles over auto-generated ones
  const track = english.find((t) => t.kind !== "asr") ?? english.find((t) => t.kind === "asr");
  if (!track) return { ok: false, code: "no-english-captions", message: "No English captions" };

  const xmlRes = await fetch(track.baseUrl, { headers: { "User-Agent": ANDROID_UA } });
  if (!xmlRes.ok) throw new Error(`Captions responded ${xmlRes.status}`);

  return {
    ok: true,
    captions: {
      title: player.videoDetails?.title ?? videoId,
      autoGenerated: track.kind === "asr",
      lines: parseTimedText(await xmlRes.text()),
    },
  };
}

function decodeXmlEntities(text: string): string {
  return text
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
}

/** Parses YouTube "timedtext" format 3: `<p t="ms" d="ms">text or <s>word</s>…</p>` */
function parseTimedText(xml: string): YoutubeCaptionLine[] {
  const lines: YoutubeCaptionLine[] = [];
  for (const m of xml.matchAll(/<p\b([^>]*)>([\s\S]*?)<\/p>/g)) {
    const attrs = m[1];
    // a="1" marks empty "append" paragraphs in auto-generated tracks
    if (/\ba="1"/.test(attrs)) continue;
    const t = Number(attrs.match(/\bt="(\d+)"/)?.[1]);
    const d = Number(attrs.match(/\bd="(\d+)"/)?.[1] ?? 0);
    const text = decodeXmlEntities(m[2].replace(/<[^>]+>/g, "")).replace(/\s+/g, " ").trim();
    if (!Number.isNaN(t) && text) lines.push({ start: t / 1000, end: (t + d) / 1000, text });
  }
  return lines;
}
